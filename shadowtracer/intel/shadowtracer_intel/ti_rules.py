"""ShadowTracer TI rule file and list set (THREAT_INTEL.md §4.3, §4.10).

The rule file only changes with ShadowTracer releases; feeds change the LIST contents.
Both are distributed together by safe_reload.py.

- File name sorts after every 0xxx-*.xml parent file (rule_order.py explains why).
- Every rule is a child of a native rule with accuracy="0", so it runs after every native
  sibling and only fires when none of them matched (§1.4); it never pre-empts one.
- Two confidence bands per observable type: -high (level 12), -medium (level 8).
- address_match_key_value is never used (inverted in 4.14.8, §0.1).
- Only the observables the lab can match today (§1.10): sshd source IPs, FIM hashes.
"""
from xml.sax.saxutils import escape

LIST_DIR = "etc/lists/shadowtracer-ti"
RULES_FILE = "etc/rules/1000-shadowtracer_ti_rules.xml"
FIRST_RULE_ID = 110000          # ShadowTracer TI range 110000-110999
BANDS = (("high", 12), ("medium", 8))
LIST_TYPES = ("ipv4", "ipv6", "domain", "url", "md5", "sha1", "sha256")
# A key no normalised IOC can ever equal (no dots, not hex): keeps every list non-empty
# so it always compiles and its rules always load (§4.3).
EMPTY_LIST_KEY = "shadowtracer-ti-empty-list"

# (native parent rule ids, decoded field, list type, lookup, description of the event)
# Parents are where an event ends WITHOUT an alert (THREAT_INTEL.md §1.4): the grouping
# parent 5700 (no sshd child matched), the level-0 leaf 5722 "Connection closed"
# (srcip decoded, wazuh-logtest 2026-11-06), and the firewall grouping rule 4100
# (iptables/ulogd lines decode srcip and dstip). Alerting rules (5710, 5712, ...) get
# no TI child: ti-matcher annotates those (6.1c) so they are never replaced.
ATTACHMENTS = (
    ("5700, 5722", "srcip", "ipv4", "address_match_key", "sshd event"),
    ("5700, 5722", "srcip", "ipv6", "match_key", "sshd event"),
    ("4100", "dstip", "ipv4", "address_match_key", "outbound connection"),
    ("4100", "dstip", "ipv6", "match_key", "outbound connection"),
    ("4100", "srcip", "ipv4", "address_match_key", "inbound connection"),
    ("4100", "srcip", "ipv6", "match_key", "inbound connection"),
    ("550, 554", "sha256", "sha256", "match_key", "FIM file"),
    ("550, 554", "sha1", "sha1", "match_key", "FIM file"),
    ("550, 554", "md5", "md5", "match_key", "FIM file"),
)


# 6.3: a malicious VirusTotal verdict (vt.py sends it in Wazuh's own integration shape,
# decoded by 0490's 87100 and matched by 87105) becomes ONE ShadowTracer TI alert: this
# child replaces 87105's alert for the same event. 87105 has no frequency dependants.
VT_RULE_ID = 110100


def list_names() -> list:
    return [f"{t}-{band}" for t in LIST_TYPES for band, _ in BANDS]


def list_paths() -> list:
    return [f"{LIST_DIR}/{name}" for name in list_names()]


def placeholder_list() -> bytes:
    return f"{EMPTY_LIST_KEY}:\n".encode()


def rules_xml() -> str:
    out = ["<!-- ShadowTracer threat intelligence rules. Generated by shadowtracer_intel/ti_rules.py;",
           "     do not edit by hand. See shadowtracer/docs/design/THREAT_INTEL.md §4.3. -->",
           '<group name="shadowtracer_ti,">']
    rule_id = FIRST_RULE_ID
    for parents, field, list_type, lookup, what in ATTACHMENTS:
        for band, level in BANDS:
            out += [
                f'  <rule id="{rule_id}" level="{level}" accuracy="0">',
                f"    <if_sid>{parents}</if_sid>",
                f'    <list field="{field}" lookup="{lookup}">{LIST_DIR}/{list_type}-{band}</list>',
                f"    <description>{escape(f'Threat intel ({band} confidence): {what} {field} $({field}) is a known indicator')}</description>",
                f"    <group>ti_{band},</group>",
                "  </rule>",
            ]
            rule_id += 1
    out += [
        f'  <rule id="{VT_RULE_ID}" level="12" accuracy="0">',
        "    <if_sid>87105</if_sid>",
        "    <field name=\"virustotal.origin\">^shadowtracer$</field>",
        "    <description>Threat intel (VirusTotal): $(virustotal.source.file) is malicious - $(virustotal.positives)/$(virustotal.total) engines ($(virustotal.labels))</description>",
        "    <group>ti_high,ti_virustotal,</group>",
        "    <options>no_full_log</options>",
        "  </rule>",
    ]
    out.append("</group>")
    return "\n".join(out) + "\n"


def bundle(lists: dict = None) -> dict:
    """{path relative to the install dir: bytes}. lists: {list name: bytes}; missing
    lists get the placeholder."""
    lists = lists or {}
    files = {f"{LIST_DIR}/{name}": lists.get(name, placeholder_list()) for name in list_names()}
    files[RULES_FILE] = rules_xml().encode()
    return files
